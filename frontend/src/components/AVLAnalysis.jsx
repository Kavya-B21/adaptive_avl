function StatCard({ label, value }) {
  return (
    <div className="stat-card">
      <span className="stat-label">{label}</span>
      <strong className="stat-value">{value}</strong>
    </div>
  );
}

function Percentage({ value }) {
  const numericValue = Number(value);

  if (!Number.isFinite(numericValue)) {
    return <strong>0.00%</strong>;
  }

  return <strong>{(numericValue * 100).toFixed(2)}%</strong>;
}

function NumberValue({ value }) {
  const numericValue = Number(value);

  if (!Number.isFinite(numericValue)) {
    return <strong>0</strong>;
  }

  return <strong>{numericValue}</strong>;
}

/*
 * Symmetry rules used by the project:
 *
 * LL -> LL   mirrored: No
 * RR -> LL   mirrored: Yes
 * LR -> LR   mirrored: No
 * RL -> LR   mirrored: Yes
 */
const SYMMETRY_MAP = {
  LL: {
    symmetric: "RR",
    canonical: "LL",
    mirrored: false,
  },

  RR: {
    symmetric: "LL",
    canonical: "LL",
    mirrored: true,
  },

  LR: {
    symmetric: "RL",
    canonical: "LR",
    mirrored: false,
  },

  RL: {
    symmetric: "LR",
    canonical: "LR",
    mirrored: true,
  },
};

/*
 * Build symmetry results from the ACTUAL rotation cases
 * generated by the current AVL workload.
 */
function getObservedMappings(rotationCases) {
  const cases = ["LL", "RR", "LR", "RL"];

  return cases
    .map((rotationCase) => {
      const count = Number(rotationCases[rotationCase] ?? 0);

      const mapping = SYMMETRY_MAP[rotationCase];

      return {
        original: rotationCase,
        symmetric: mapping.symmetric,
        canonical: mapping.canonical,
        mirrored: mapping.mirrored,
        count: Number.isFinite(count) ? count : 0,
      };
    })
    .filter((item) => item.count > 0);
}

